export default function ToolIcon({ name, size = 22 }: { name: string; size?: number }) {
  const Cmp = ICONS[name];
  // 名前を間違えても落とさない。アイコンが出ないだけで済ませる
  if (!Cmp) return null;
  // 線の太さはサイト全体で regular に統一する
  return <Cmp size={size} weight="regular" aria-hidden="true" />;
}
