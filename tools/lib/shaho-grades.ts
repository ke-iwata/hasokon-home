/**
 * 厚生年金の標準報酬月額の下限・上限。
 * 健康保険は58,000円〜1,390,000円（50等級）だが、厚生年金は
 * 88,000円（1等級）〜650,000円（32等級）で頭打ちになる。
 *
 * 【データ更新箇所】厚生年金の等級が追加されたらここ
 */
export const PENSION_STANDARD_MIN = 88_000;
export const PENSION_STANDARD_MAX = 650_000;

/** 月収（額面）から等級表の行を引く。[等級, 標準報酬月額, 下限, 上限] */
export function gradeOf(monthlyIncome: number): readonly [number, number, number, number] {
  for (const g of GRADES) {
    if (monthlyIncome >= g[2] && monthlyIncome < g[3]) return g;
  }
  return GRADES[GRADES.length - 1];
}

/** 月収（額面）から健康保険の標準報酬月額を求める */
export function standardMonthly(monthlyIncome: number): number {
  return gradeOf(monthlyIncome)[1];
}

/**
 * 月収（額面）から厚生年金の標準報酬月額を求める。
 * 健康保険の等級を引いたうえで、厚生年金側の下限・上限に丸める。
 */
export function pensionStandardMonthly(monthlyIncome: number): number {
  const std = standardMonthly(monthlyIncome);
  return Math.min(PENSION_STANDARD_MAX, Math.max(PENSION_STANDARD_MIN, std));
}

/**
 * 被保険者負担分の端数処理（50銭以下切り捨て・50銭超切り上げ）
 * ※実際の給与では健康保険料と合算後に端数処理されるため±1円の誤差が出ることがある
 */
export function roundPremium(value: number): number {
  const frac = value - Math.floor(value);
  return frac > 0.5 ? Math.ceil(value) : Math.floor(value);
}
