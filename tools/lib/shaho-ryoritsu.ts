/**
 * 本文に出す料率の文字列（「4.95%」など）。
 *
 * **本文の数字をここから出すためのもの。** 定数だけ直して説明文を直し忘れると、
 * 画面上は「雇用保険0.55%で概算します」と書いてあるのに計算は0.5%、という
 * 食い違いが起きる（2026-09-19に、実際に本番で起きていたのを見つけた）。
 *
 * 保険料調整制度の本人負担の割合（0.25 → 「25%」・0.375 → 「37.5%」）も同じ形なので、
 * 画面に出すときはこれを通すこと。**自前で 100 を掛けないこと**
 * （`Math.round(share * 100) / 100` と書いて 0.25 をそのまま出す取り違えを実際にやった）。
 */
export function ratePercent(rate: number): string {
  // 料率は小数第2位までで表せる範囲しか使わない（4.95% / 9.15% / 0.5% / 37.5%）
  return `${Number((rate * 100).toFixed(2))}%`;
}
