/**
 * JIS 慣用色名の sRGB 近似値を作るスクリプト（手動で回す。CI には入れない）。
 *
 *   node scripts/gen-jis-color-names.mjs [real.dat のパス]
 *
 * 出力: lib/color/jis-names.ts（生成物。手で直さない）
 *
 * ■ 使うもの
 * - **名前とマンセル値だけ**：JIS Z 8102:2001「物体色の色名」付表1 の慣用色名（269 色。うち金色・銀色は
 *   マンセル値が無いので除く）。規格票は日本規格協会の著作物なので、表（名前＋マンセル値＋説明）を
 *   丸ごと写さない。説明文は持たない
 * - **Munsell Renotation Data（`real.dat`）**：RIT Munsell Color Science Laboratory が公開している、
 *   マンセル値 → CIE xyY（C光源）の表。https://www.rit-mcsl.org/MunsellRenotation/real.dat
 *   引数でパスを渡さなければ、この URL から取ってくる
 * - **他サイトの色見本の値は使わない**
 *
 * ■ 換算の手順（どれも近似）
 * 1. 明度 V → 輝度 Y：ASTM D1535 の5次式（完全拡散反射面を 100）
 * 2. 色度 xy：real.dat の格子（色相 2.5 刻み・明度 1 刻み・彩度 2 刻み）を補間する
 *    - 彩度：同じ色相・明度で隣り合う2点を直線補間。彩度 2 未満は C光源の白色点と彩度 2 の間を補間。
 *      表の外（彩度が高すぎる）は端の2点から外挿
 *    - 色相：白色点のまわりの極座標（距離と角度）で補間
 *    - 明度：隣り合う整数の明度の xy を、輝度 Y の比で補間。9 を超える明度は 9 の色度を使う
 * 3. XYZ（C光源）→ Bradford 変換で D65 に順応 → 線形 sRGB → sRGB のガンマ → 0〜255 に切り詰めて丸める
 *
 * sRGB の色域の外にある色は切り詰めるので、元の色より鈍くなることがある。
 * 画面には「近似」と表示する（「JIS の規定値」とは書かない）。
 *
 * 仕様: docs/features/color-code-contrast.md
 */
