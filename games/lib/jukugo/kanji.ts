export interface KanjiInfo {
  grade: KanjiGrade;
  /** 音訓（ひらがな）。音読みが先、訓読みが後 */
  readings: readonly string[];
}

function parse(raw: string): Map<string, KanjiInfo> {
  const map = new Map<string, KanjiInfo>();
  for (const line of raw.split('\n')) {
    if (!line) continue;
    const ch = String.fromCodePoint(line.codePointAt(0)!);
    const rest = line.slice(ch.length);
    const grade = Number(rest[0]) as KanjiGrade;
    map.set(ch, { grade, readings: rest.slice(1).split(',').filter(Boolean) });
  }
  return map;
}

/** 常用漢字 2,136 字 → 学年と音訓 */
export const KANJI: ReadonlyMap<string, KanjiInfo> = parse(RAW);

/** 常用漢字表にある字か */
export function isJoyo(ch: string): boolean {
  return KANJI.has(ch);
}

/** 教育漢字（学年別漢字配当表の 1,026 字）か */
export function isKyoiku(ch: string): boolean {
  const info = KANJI.get(ch);
  return info !== undefined && info.grade <= 6;
}

/** 学年。常用漢字でなければ undefined */
export function gradeOf(ch: string): KanjiGrade | undefined {
  return KANJI.get(ch)?.grade;
}

/** 音訓。常用漢字でなければ空 */
export function readingsOf(ch: string): readonly string[] {
  return KANJI.get(ch)?.readings ?? [];
}
