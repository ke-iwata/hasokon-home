/** レベル別の出題語彙。**必ずこの `WORDS` を通す**（配列を直に参照しない） */
export const WORDS: Record<Level, readonly string[]> = {
  easy: EASY,
  normal: NORMAL,
  hard: HARD,
};

/** ひらがなだけでできているか（長音符「ー」と小書きの「ゕゖ」は認めない） */
export function isHiraganaOnly(word: string): boolean {
  return /^[ぁ-ゖ]+$/.test(word) && !/[ゕゖ]/.test(word);
}

/** むずかしいの条件（促音か拗音を含む）を満たすか */
export function hasSokuonOrYoon(word: string): boolean {
  return /[っゃゅょ]/.test(word);
}

/** 語彙リストとして正しいか（テストとビルド時の自己点検で使う） */
export function invalidWords(level: Level): string[] {
  const { min, max } = LENGTH_RANGE[level];
  return WORDS[level].filter(
    (word) =>
      !isHiraganaOnly(word) ||
      word.length < min ||
      word.length > max ||
      !isTypableKana(word) ||
      (level === 'hard' && !hasSokuonOrYoon(word)),
  );
}
