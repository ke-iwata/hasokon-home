/**
 * タイピング練習の出題語彙
 *
 * 仕様: docs/features/game-typing.md
 *
 * ## なぜデータとして持つか
 *
 * `tools/lib/password-words.ts`（パスワード生成の日本語ワードリスト）で
 * 確立した「**語彙をデータで持ち、品質はテストで固定する**」型を踏襲している。
 * 出題を生成規則で作ると、読めない語や意味の通らない語が混ざるのを
 * 止められない。ここに並べておけば、増やすのも直すのも1か所で済む。
 *
 * ## 語を足すときの約束（`tests/typing-words.test.ts` が落とす）
 *
 * - **ひらがなだけ**（カタカナ・漢字・長音符「ー」・記号を混ぜない）。
 *   長音符は打鍵の対応が環境で割れるので、伸ばす音は「う」「お」で書く
 * - **レベルごとの長さの範囲に収める**（下の `LENGTH_RANGE`）
 * - **重複させない**（レベルをまたいでも同じ語を出さない）
 * - **`lib/typing-romaji.ts` の変換表で打てること**。
 *   打てない文字が混ざっていたらテストが落ちる
 * - **むずかしいは促音「っ」か拗音（ゃゅょ）を必ず含める**。
 *   長いだけの語では、このレベルの狙い（判定の山場を練習する）にならない
 */

